arr = [10, 20, 30, 40, 50]

# Add element
arr.append(60)
print("After adding:", arr)

# Remove element
arr.remove(30)
print("After removing:", arr)

# Access element
print("First element:", arr[0])

# Find length
print("Length:", len(arr))

# Reverse array
arr.reverse()
print("Reversed:", arr)